"""Lesson 1: run a Python file, print values, and read comments."""

# Python ignores a comment. Comments explain code to human readers.
print("Hello, Python!")

# Text inside matching quotes is called a string.
print("I can run a Python 3 program.")

# print can display numbers too.
print(2 + 3)

# A comma lets print display several values with spaces between them.
print("The answer is", 5)

# assert checks that an expression is True.
assert 2 + 3 == 5

print("Lesson 1 checks passed.")
